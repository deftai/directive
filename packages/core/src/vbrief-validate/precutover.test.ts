import { chmodSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import {
  detectPreCutover,
  detectPreCutoverLegacy,
  frozenPreCutoverMigrationGuidance,
  isCurrentGeneratedSpecification,
  isDeprecationRedirect,
  isGeneratedSpecificationExport,
  missingLifecycleFolders,
  renderPrecutoverLine,
} from "./precutover.js";

const temps: string[] = [];
afterEach(() => {
  for (const dir of temps.splice(0)) {
    rmSync(dir, { recursive: true, force: true });
  }
});

describe("precutover helpers", () => {
  it("isDeprecationRedirect accepts both sentinel forms", () => {
    expect(isDeprecationRedirect("<!-- deft:deprecated-redirect -->")).toBe(true);
    expect(isDeprecationRedirect("<!-- Purpose: deprecation redirect -->")).toBe(true);
    expect(isDeprecationRedirect("# real content")).toBe(false);
  });

  it("detectPreCutoverLegacy lists legacy root markdown files", () => {
    const base = mkdtempSync(join(tmpdir(), "precutover-"));
    temps.push(base);
    writeFileSync(join(base, "SPECIFICATION.md"), "# spec\n", "utf8");
    writeFileSync(join(base, "PROJECT.md"), "# project\n", "utf8");
    expect(detectPreCutoverLegacy(base)).toEqual(["SPECIFICATION.md", "PROJECT.md"]);
  });

  it("detectPreCutoverLegacy ignores deprecation redirects", () => {
    const base = mkdtempSync(join(tmpdir(), "precutover-"));
    temps.push(base);
    writeFileSync(join(base, "SPECIFICATION.md"), "<!-- deft:deprecated-redirect -->\n", "utf8");
    expect(detectPreCutoverLegacy(base)).toEqual([]);
  });

  it("detectPreCutoverLegacy does not throw on unreadable markdown files", () => {
    const base = mkdtempSync(join(tmpdir(), "precutover-"));
    temps.push(base);
    const specPath = join(base, "SPECIFICATION.md");
    writeFileSync(specPath, "# spec\n", "utf8");
    if (process.platform !== "win32") {
      chmodSync(specPath, 0o000);
      expect(() => detectPreCutoverLegacy(base)).not.toThrow();
      chmodSync(specPath, 0o644);
    } else {
      expect(detectPreCutoverLegacy(base)).toContain("SPECIFICATION.md");
    }
  });

  it("missingLifecycleFolders reports absent lifecycle dirs", () => {
    const base = mkdtempSync(join(tmpdir(), "precutover-"));
    temps.push(base);
    mkdirSync(join(base, "xbrief"), { recursive: true });
    writeFileSync(join(base, "xbrief", "seed.xbrief.json"), "{}", { encoding: "utf8" });
    expect(missingLifecycleFolders(base)).toEqual([
      "proposed",
      "pending",
      "active",
      "completed",
      "cancelled",
    ]);
  });

  it("isGeneratedSpecificationExport requires source vbrief file", () => {
    const base = mkdtempSync(join(tmpdir(), "precutover-"));
    temps.push(base);
    const content =
      "<!-- Purpose: rendered specification -->\n<!-- Source of truth: xbrief/specification.xbrief.json -->\n";
    expect(isGeneratedSpecificationExport(base, content)).toBe(false);
    mkdirSync(join(base, "xbrief"), { recursive: true });
    writeFileSync(
      join(base, "xbrief", "specification.xbrief.json"),
      '{"xBRIEFInfo":{"version":"0.8"},"plan":{"title":"x","status":"running","narratives":{},"items":[]}}',
      "utf8",
    );
    expect(isGeneratedSpecificationExport(base, content)).toBe(true);
  });

  it("isGeneratedSpecificationExport recognizes xbrief layout (#2205)", () => {
    const base = mkdtempSync(join(tmpdir(), "precutover-xbrief-"));
    temps.push(base);
    for (const folder of ["proposed", "pending", "active", "completed", "cancelled"]) {
      mkdirSync(join(base, "xbrief", folder), { recursive: true });
    }
    writeFileSync(
      join(base, "xbrief", "specification.xbrief.json"),
      '{"xBRIEFInfo":{"version":"0.8"},"plan":{"title":"x","status":"running","narratives":{},"items":[]}}',
      "utf8",
    );
    const content =
      "<!-- AUTO-GENERATED by task spec:render -->\n" +
      "<!-- Purpose: rendered specification -->\n" +
      "<!-- Source of truth: xbrief/specification.xbrief.json -->\n";
    expect(isGeneratedSpecificationExport(base, content)).toBe(true);
    expect(isCurrentGeneratedSpecification(base, content)).toBe(true);
  });

  it("isGeneratedSpecificationExport rejects an unrelated existing source artifact", () => {
    const base = mkdtempSync(join(tmpdir(), "precutover-source-binding-"));
    temps.push(base);
    mkdirSync(join(base, "xbrief"), { recursive: true });
    const resolvedSpec =
      '{"xBRIEFInfo":{"version":"0.8"},"plan":{"title":"resolved","status":"running","narratives":{},"items":[]}}';
    writeFileSync(join(base, "xbrief", "specification.xbrief.json"), resolvedSpec, "utf8");
    mkdirSync(join(base, "inputs"), { recursive: true });
    const unrelated = join(base, "inputs", "unrelated.json");
    writeFileSync(
      unrelated,
      '{"xBRIEFInfo":{"version":"0.8"},"plan":{"title":"unrelated","status":"running","narratives":{},"items":[]}}',
      "utf8",
    );
    const content =
      "<!-- Purpose: rendered specification -->\n" +
      `<!-- Source of truth: ${unrelated.replaceAll("\\", "/")} -->\n`;

    expect(isGeneratedSpecificationExport(base, content)).toBe(false);
  });

  it("detectPreCutover does not flag xbrief-migrated project with generated SPECIFICATION.md (#2205)", () => {
    const base = mkdtempSync(join(tmpdir(), "precutover-xbrief-clean-"));
    temps.push(base);
    for (const folder of ["proposed", "pending", "active", "completed", "cancelled"]) {
      mkdirSync(join(base, "xbrief", folder), { recursive: true });
    }
    writeFileSync(
      join(base, "xbrief", "specification.xbrief.json"),
      '{"xBRIEFInfo":{"version":"0.8"},"plan":{"title":"x","status":"running","narratives":{},"items":[]}}',
      "utf8",
    );
    writeFileSync(
      join(base, "xbrief", "PROJECT-DEFINITION.xbrief.json"),
      '{"xBRIEFInfo":{"version":"0.8"},"plan":{"title":"x","status":"running","narratives":{},"items":[]}}',
      "utf8",
    );
    writeFileSync(
      join(base, "SPECIFICATION.md"),
      "<!-- AUTO-GENERATED by task spec:render -->\n" +
        "<!-- Purpose: rendered specification -->\n" +
        "<!-- Source of truth: xbrief/specification.xbrief.json -->\n# Spec\n",
      "utf8",
    );
    expect(detectPreCutover(base)).toEqual({ preCutover: false, reasons: [] });
    expect(renderPrecutoverLine(base)).toContain("Pre-cutover: none");
  });

  it("isCurrentGeneratedSpecification passes with full lifecycle layout", () => {
    const base = mkdtempSync(join(tmpdir(), "precutover-"));
    temps.push(base);
    for (const folder of ["proposed", "pending", "active", "completed", "cancelled"]) {
      mkdirSync(join(base, "xbrief", folder), { recursive: true });
    }
    writeFileSync(
      join(base, "xbrief", "specification.xbrief.json"),
      '{"xBRIEFInfo":{"version":"0.8"},"plan":{"title":"x","status":"running","narratives":{},"items":[]}}',
      "utf8",
    );
    const content =
      "<!-- Purpose: rendered specification -->\n<!-- Source of truth: xbrief/specification.xbrief.json -->\n";
    expect(isCurrentGeneratedSpecification(base, content)).toBe(true);
  });

  it("detectPreCutover ignores redirect PROJECT.md", () => {
    const base = mkdtempSync(join(tmpdir(), "precutover-"));
    temps.push(base);
    writeFileSync(join(base, "PROJECT.md"), "<!-- Purpose: deprecation redirect -->\n", "utf8");
    expect(detectPreCutover(base)).toEqual({ preCutover: false, reasons: [] });
  });

  it("detectPreCutover flags legacy PROJECT.md", () => {
    const base = mkdtempSync(join(tmpdir(), "precutover-"));
    temps.push(base);
    writeFileSync(join(base, "PROJECT.md"), "# legacy\n", "utf8");
    const result = detectPreCutover(base);
    expect(result.preCutover).toBe(true);
    expect(result.reasons.some((r) => r.includes("PROJECT.md"))).toBe(true);
  });

  it("detectPreCutover aggregates legacy markdown and missing lifecycle reasons", () => {
    const base = mkdtempSync(join(tmpdir(), "precutover-"));
    temps.push(base);
    writeFileSync(join(base, "SPECIFICATION.md"), "# spec\n", "utf8");
    mkdirSync(join(base, "xbrief"), { recursive: true });
    writeFileSync(join(base, "xbrief", "seed.xbrief.json"), "{}", { encoding: "utf8" });
    const result = detectPreCutover(base);
    expect(result.preCutover).toBe(true);
    expect(result.reasons.some((r) => r.includes("SPECIFICATION.md"))).toBe(true);
    expect(result.reasons.some((r) => r.includes("lifecycle folder"))).toBe(true);
    expect(result.reasons.some((r) => r.includes("xbrief/"))).toBe(true);
  });

  it("renderPrecutoverLine teaches directive upgrade when pre-cutover (F-017 / AC8.9)", () => {
    const base = mkdtempSync(join(tmpdir(), "precutover-"));
    temps.push(base);
    writeFileSync(join(base, "PROJECT.md"), "# project\n", "utf8");
    const line = renderPrecutoverLine(base);
    expect(line).toContain("Pre-cutover:");
    expect(line).toContain("directive upgrade");
    // May mention historical migrate:vbrief as diagnostic fact; must not prescribe it.
    expect(line).not.toMatch(/run `task migrate:vbrief`/);
    expect(line).not.toContain("deft migrate:xbrief");
    expect(line).toMatch(/no longer the taught path|Diagnostic note/i);
  });

  it("renderPrecutoverLine reports clean state for greenfield layout", () => {
    const base = mkdtempSync(join(tmpdir(), "precutover-"));
    temps.push(base);
    for (const folder of ["proposed", "pending", "active", "completed", "cancelled"]) {
      mkdirSync(join(base, "xbrief", folder), { recursive: true });
    }
    expect(renderPrecutoverLine(base)).toContain("Pre-cutover: none");
  });

  it("frozenPreCutoverMigrationGuidance teaches directive upgrade (F-017 / AC8.9)", () => {
    const guidance = frozenPreCutoverMigrationGuidance();
    expect(guidance).toContain("directive upgrade");
    expect(guidance).toContain("#2068");
    expect(guidance).toContain("v0.59.0"); // diagnostic fact only
    expect(guidance).not.toMatch(/run `task migrate:vbrief`/);
    expect(guidance).not.toContain("deft migrate:xbrief");
    expect(guidance).toMatch(/no longer the taught path/i);
  });

  it("frozenPreCutoverMigrationGuidance names the fresh-start fallback (#2297 / F-017)", () => {
    const guidance = frozenPreCutoverMigrationGuidance();
    expect(guidance).toContain("directive init");
    expect(guidance).toContain("directive upgrade");
    // Historical two-hop is no longer the primary taught recovery.
    expect(guidance).not.toMatch(/Best-effort path/);
  });
});
